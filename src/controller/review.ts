import { createHash } from "node:crypto";
import { planRelease } from "../release/core.ts";
import type { Change } from "../release/core.ts";

export interface ReviewInput {
  readonly producer: string;
  readonly repository: string;
  readonly branch: string;
  readonly baseline: string;
  readonly source: string;
  readonly previousVersion: string | null;
  readonly changes: readonly Change[];
  readonly files: ReadonlyMap<string, string | Uint8Array>;
}

export interface ReviewRecord {
  readonly schema: 1;
  readonly producer: string;
  readonly repository: string;
  readonly branch: string;
  readonly baseline: string;
  readonly source: string;
  readonly previousVersion: string | null;
  readonly changes: readonly Change[];
  readonly version: string;
  readonly markdown: string;
  readonly files: readonly { readonly path: string; readonly sha256: string }[];
}

const sha = /^(?:[a-f0-9]{40}|[a-f0-9]{64})$/u;
function fileHashes(files: ReadonlyMap<string, string | Uint8Array>) {
  return [...files]
    .map(([path, contents]) => {
      if (
        !path ||
        path.startsWith("/") ||
        path
          .split("/")
          .some(
            (part) => !part || part === "." || part === ".." || part.toLowerCase() === ".git",
          ) ||
        path.includes("\\") ||
        path.includes("\0")
      )
        throw new Error("Review contains an invalid file path.");
      return { path, sha256: createHash("sha256").update(contents).digest("hex") };
    })
    .toSorted((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

export function createReview(input: ReviewInput): ReviewRecord {
  if (
    !sha.test(input.producer) ||
    !sha.test(input.baseline) ||
    !sha.test(input.source) ||
    !input.branch ||
    /[\0\r\n]/u.test(input.branch)
  )
    throw new Error("Review requires immutable baseline and source commit IDs and a branch.");
  const plan = planRelease(input);
  if (plan.kind !== "release") throw new Error("A pending range cannot authorize a release.");
  return {
    schema: 1,
    producer: input.producer,
    repository: input.repository,
    branch: input.branch,
    baseline: input.baseline,
    source: input.source,
    previousVersion: input.previousVersion,
    changes: structuredClone(input.changes).toSorted((a, b) => a.number - b.number),
    version: plan.version,
    markdown: plan.markdown,
    files: fileHashes(input.files),
  };
}

// The changelog already contains the reviewed Markdown. Persist only its digest.
export function serializeReview(review: ReviewRecord): string {
  const { markdown: _markdown, ...evidence } = review;
  return JSON.stringify(evidence, null, 2) + "\n";
}

/** Check reproduction against independently supplied captured inputs and generated bytes.
 * The caller must separately authenticate ownership, refs, parents, and landed tree. */
export function verifyReview(record: unknown, expected: ReviewInput): ReviewRecord {
  const computed = createReview(expected);
  if (JSON.stringify(record, null, 2) + "\n" !== serializeReview(computed))
    throw new Error(
      "Reviewed release record does not match the captured inputs and generated files.",
    );
  return computed;
}
