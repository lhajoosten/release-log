import assert from "node:assert/strict";
import test from "node:test";
import { createReview, serializeReview, verifyReview } from "../src/controller/review.ts";

const input = {
  producer: "c".repeat(40),
  repository: "acme/widget",
  branch: "main",
  baseline: "a".repeat(40),
  source: "b".repeat(40),
  previousVersion: "1.2.3",
  changes: [{ number: 41, title: "feat: add widgets", author: "alice", requiredAction: null }],
  files: new Map([["CHANGELOG.md", "reviewed changelog\n"]]),
};

void test("review reproduces the release and rejects altered evidence or generated bytes", () => {
  const record = createReview(input);
  assert.equal(record.version, "1.3.0");
  assert.match(record.markdown, /add widgets/u);
  const evidence: unknown = JSON.parse(serializeReview(record));
  assert.deepEqual(verifyReview(evidence, input), record);
  assert.throws(() => verifyReview({ ...record, version: "2.0.0" }, input), /does not match/u);
  assert.throws(
    () => verifyReview(evidence, { ...input, files: new Map([["CHANGELOG.md", "tampered\n"]]) }),
    /does not match/u,
  );
  assert.throws(
    () =>
      verifyReview(evidence, {
        ...input,
        changes: [{ ...input.changes[0]!, title: "fix: changed" }],
      }),
    /does not match/u,
  );
});

void test("pending changes and unsafe generated paths cannot authorize a review", () => {
  assert.throws(
    () => createReview({ ...input, changes: [{ ...input.changes[0]!, title: "docs: update" }] }),
    /pending/u,
  );
  assert.throws(
    () => createReview({ ...input, files: new Map([["../CHANGELOG.md", "x"]]) }),
    /invalid file path/u,
  );
});

void test("image publication opt-out is captured and cannot be added or removed from reviewed evidence", () => {
  const defaultRecord = createReview(input);
  assert.equal(Object.hasOwn(defaultRecord, "publishImage"), false);
  const noImage = { ...input, publishImage: false as const };
  const record = createReview(noImage);
  const evidence: unknown = JSON.parse(serializeReview(record));
  assert.equal(record.publishImage, false);
  assert.deepEqual(verifyReview(evidence, noImage), record);
  assert.throws(() => verifyReview(evidence, input), /does not match/u);
  assert.throws(
    () => verifyReview(JSON.parse(serializeReview(defaultRecord)), noImage),
    /does not match/u,
  );
});
