import assert from "node:assert/strict";
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { planPoetryWorkspace } from "../src/release/poetry-workspace.ts";

void test("Poetry path projects update their lock and stale content hashes block", async () => {
  const root = await mkdtemp(join(tmpdir(), "poetry-workspace-"));
  try {
    await mkdir(join(root, "packages/alpha"), { recursive: true });
    await writeFile(
      join(root, "pyproject.toml"),
      '[tool.poetry]\nname = "poetry-check-root"\nversion = "1.2.3"\ndescription = "fixture"\nauthors = ["Test <test@example.invalid>"]\n\n[tool.poetry.dependencies]\npython = ">=3.10"\nalpha-check = { path = "packages/alpha", develop = true }\n',
    );
    await writeFile(
      join(root, "packages/alpha/pyproject.toml"),
      '[tool.poetry]\nname = "alpha-check"\nversion = "1.2.3"\n',
    );
    const lock =
      '[[package]]\nname = "alpha-check"\nversion = "1.2.3"\n[package.source]\ntype = "directory"\nurl = "packages/alpha"\n\n[metadata]\nlock-version = "2.1"\ncontent-hash = "515d16e3f1bd91dd9e865acd5cdfb72a95396525be2e9060d1a978274e439a84"\n';
    await writeFile(join(root, "poetry.lock"), lock);
    const files = await planPoetryWorkspace(root, "1.2.3", "1.3.0");
    assert.equal(files?.size, 3);
    assert.equal(files?.get("poetry.lock"), lock.replace('version = "1.2.3"', 'version = "1.3.0"'));
    await writeFile(join(root, "poetry.lock"), lock.replace("515d16e3", "00000000"));
    await assert.rejects(planPoetryWorkspace(root, "1.2.3", "1.3.0"), /stale or unsupported/u);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

void test("Poetry updates sourced requirements while preserving comments and registry packages", async () => {
  const root = await mkdtemp(join(tmpdir(), "poetry-deps-"));
  try {
    await mkdir(join(root, "packages/alpha"), { recursive: true });
    await writeFile(
      join(root, "pyproject.toml"),
      '[project]\nname = "poetry-check-root"\nversion = "1.5.0" # note 1.5.0\nrequires-python = ">=3.10"\ndependencies = ["alpha-check>=1.5.0"]\n[tool.poetry.dependencies]\nalpha-check = { path = "packages/alpha", develop = true }\n',
    );
    await writeFile(
      join(root, "packages/alpha/pyproject.toml"),
      '[tool.poetry]\nname = "alpha-check"\nversion = "1.5.0"\ndescription = "fixture"\nauthors = ["Test <test@example.invalid>"]\n',
    );
    await writeFile(
      join(root, "poetry.lock"),
      '# This file is automatically @generated by Poetry 2.1.3 and should not be changed by hand.\n\n[[package]]\nname = "alpha-check"\nversion = "1.5.0"\ndescription = "fixture"\noptional = false\npython-versions = "*"\ngroups = ["main"]\nfiles = []\ndevelop = true\n\n[package.source]\ntype = "directory"\nurl = "packages/alpha"\n\n[[package]]\nname = "alpha-check"\nversion = "1.5.0"\nsource = { type = "legacy", url = "https://example.invalid" }\n\n[metadata]\nlock-version = "2.1"\npython-versions = ">=3.10"\ncontent-hash = "f65b4b836caadf25e03d71bc2dbdc82b0cc6cb6d7f1df8ce2f77acea76e18ba9"\n',
    );
    const files = await planPoetryWorkspace(root, "1.5.0", "1.6.0");
    assert.match(files?.get("pyproject.toml") ?? "", /version = "1.6.0" # note 1.5.0/u);
    assert.match(files?.get("pyproject.toml") ?? "", /alpha-check>=1.6.0/u);
    assert.match(
      files?.get("poetry.lock") ?? "",
      /name = "alpha-check"\nversion = "1.5.0"\nsource = \{ type = "legacy"/u,
    );
    assert.match(files?.get("poetry.lock") ?? "", /name = "alpha-check"\nversion = "1.6.0"/u);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
